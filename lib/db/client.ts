import "server-only";
import postgres from "postgres";

/**
 * Подключение к Postgres.
 *
 * Драйвер `postgres` (не `@neondatabase/serverless`) выбран осознанно:
 * тот говорит по собственному HTTP-протоколу Neon и ни с каким другим
 * Postgres не соединяется вовсе — ни с локальным в разработке, ни с
 * любым другим хостингом, если база когда-нибудь переедет. Обычный
 * протокол работает и с Neon, и с чем угодно ещё.
 *
 * Клиент ленивый — создаётся при первом запросе, а не при импорте.
 * Иначе модуль падал бы на `next build` на машине без переменной
 * окружения, а сборка обязана проходить и без базы: страницы в этом
 * случае берут значения из `DEFAULTS` (см. `lib/content.ts`).
 */

/**
 * Адрес базы. Vercel заводит переменные сам при подключении провайдера.
 *
 * `DATABASE_URL` первым: у интеграции Neon это основная переменная и
 * именно она указывает на пулер. Набор `POSTGRES_*` там же заводится
 * «для совместимости со старыми шаблонами Vercel Postgres» — как
 * запасной вариант он годится, как основной полагаться на него не стоит.
 */
function connectionString(): string | undefined {
  return process.env.DATABASE_URL ?? process.env.POSTGRES_URL;
}

/** Есть ли вообще база. Вызывается до запроса, чтобы решить про фолбэк. */
export function hasDatabase(): boolean {
  return Boolean(connectionString());
}

type SqlClient = ReturnType<typeof postgres>;

let client: SqlClient | null = null;

export function sql(): SqlClient {
  if (client) return client;

  const url = connectionString();
  if (!url) {
    throw new Error(
      "Адрес базы не задан. На Vercel его заводит интеграция Neon (Storage → Connect to Project); локально пропишите DATABASE_URL в .env.local — строку подключения возьмите в Neon, вкладка psql.",
    );
  }

  client = postgres(url, {
    /* Ровно три: столько запросов `load()` отправляет параллельно
       (программы, пакеты, настройки). Больше здесь не использовать
       нечем, а serverless-инстансы плодятся десятками — каждый лишний
       слот в пуле приближает лимит соединений базы просто так. */
    max: 3,
    idle_timeout: 20,
    /* Локальный Postgres в разработке поднят без TLS, облачный его
       требует. `prefer` закрывает оба случая: шифруем, если сервер
       умеет, и не падаем, если нет. */
    ssl: "prefer",

    /* Без подготовленных запросов — и это не микрооптимизация наоборот,
       а условие работы через пулер.

       Драйвер готовит запросы по умолчанию, а подготовленный запрос —
       это состояние конкретного серверного соединения. Пулер Neon
       (PgBouncer) работает в режиме транзакций и на следующий запрос
       выдаёт уже другое соединение. Под нагрузкой это даёт пару
       чередующихся ошибок: `prepared statement "s1" already exists` и
       `... does not exist` — то есть падения, которых нет на спокойном
       трафике и которые не воспроизводятся локально.

       Цена — разбор запроса на каждый вызов. Запросов здесь три на
       пересборку страницы, и та случается после правки в админке. */
    prepare: false,
  });

  return client;
}

/**
 * Запрос с мягким отказом: вернуть `null` вместо исключения.
 *
 * Сайт — лендинги, и упавшая база не повод отдавать посетителю 500:
 * цифры прошлого потока хуже свежих, но лучше пустой страницы. Поэтому
 * чтение контента идёт через эту обёртку, а запись в админке — нет:
 * там молчаливый отказ был бы хуже ошибки.
 *
 * Отказ не молчаливый: он пишется в `console.error` и виден в логах
 * Vercel. Админка вдобавок показывает предупреждение — иначе «сайт
 * выглядит нормально» слишком долго скрывало бы, что база отвалилась.
 */
export async function tryQuery<T>(
  run: (db: SqlClient) => Promise<T>,
): Promise<T | null> {
  if (!hasDatabase()) return null;

  try {
    return await run(sql());
  } catch (error) {
    console.error("[db] запрос не прошёл, страница возьмёт значения из кода:", error);
    return null;
  }
}
