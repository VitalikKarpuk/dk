/**
 * Пункты для секции на `/individual` — те четыре, что снимают сомнения
 * до покупки. Регламент (перенос, опоздание, порядок оплаты) на лендинг
 * не выносится: он нужен уже записавшемуся и читается там мелким
 * шрифтом рядом с ценой.
 */
const KEY_RULE_IDS = [
  "confidentiality",
  "unused",
  "support",
  "responsibility",
] as const;

export const KEY_RULES: Rule[] = KEY_RULE_IDS.map(
  (id) => RULES.find((rule) => rule.id === id)!,
);

/** Номер пункта в документе — «04» рядом с заголовком и в ссылках. */
export function ruleNumber(rule: Rule) {
  return String(RULES.indexOf(rule) + 1).padStart(2, "0");
}
